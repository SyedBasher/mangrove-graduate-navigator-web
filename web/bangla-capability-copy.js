export function localizeCapability(item, lang='en') {
  if (lang !== 'bn') {
    return {
      label: item.label_en,
      question: item.question_en,
      example: item.example_en,
      options: item.options.map(o => ({ value:o.value, label:o.en })),
    };
  }
  const x = BN[item.code] || {};
  return {
    label: x.label || item.label_bn,
    question: x.question || item.question_bn,
    example: x.example || item.example_bn,
    options: item.options.map(o => ({ value:o.value, label:x.options?.[o.value] || o.bn })),
  };
}
